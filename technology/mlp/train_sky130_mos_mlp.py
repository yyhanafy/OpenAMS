def main() -> int:
    args = build_parser().parse_args()

    if args.command == "train":
        csv_path = Path(args.csv)
        output_dir = Path(args.output_dir)
        polarities = [
            item.strip().lower()
            for item in args.polarities.split(",")
            if item.strip()
        ]
        invalid = set(polarities) - {"nmos", "pmos"}
        if invalid:
            raise ValueError(f"Invalid polarities: {sorted(invalid)}")
        for polarity in polarities:
            train_polarity(csv_path, output_dir, polarity, args)
        return 0

    if args.command == "evaluate":
        evaluate_command(args)
        return 0

    if args.command == "predict":
        predict_command(args)
        return 0

    if args.command == "inspect":
        inspect_command(args)
        return 0

    raise RuntimeError(f"Unhandled command: {args.command}")


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except KeyboardInterrupt:
        print("\n[FAIL] interrupted", file=sys.stderr)
        raise SystemExit(130)
