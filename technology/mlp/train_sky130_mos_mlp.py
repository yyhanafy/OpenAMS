#!/usr/bin/env python3
"""
Train, evaluate, and query SKY130 MOS MLP surrogate models.

Designed for:
    technology/sky130_tt_27c_mlp_smoke.csv
and the later dense dataset generated by:
    technology/characterize_sky130_mlp_dataset.py

Key features
------------
- Separate NMOS and PMOS models.
- Supports both legacy DC-only and new DC+AC schemas.
- Uses a per-target mask, so missing BSIM quantities do not discard a row.
- Log transforms positive quantities spanning many decades.
- Signed asinh transforms for charges and capacitance-matrix entries.
- Saves model, scalers, transforms, split indices, metrics, and provenance.
- Supports train, evaluate, predict, and inspect commands.
"""

